enum JenisVd: string implements CeisaReferenceEnumInterface
{
    use CeisaReferenceEnumTrait;

    case BUKAN_TRANSAKSI_JUAL_BELI_LAINNYA = 'BTR';
    case BARANG_TERDIRI_DARI_BARANG_BARANG_YANG_MERUPAKAN_OBYEK = 'CAM';
