<?php

declare(strict_types=1);

namespace Src\Ceisa\Domain\Enums;

/**
 * Enum CaraBayar
 *
 * Referensi data CEISA 4.0 DJBC per regulasi resmi.
 */
enum CaraBayar: string implements CeisaReferenceEnumInterface
{
    use CeisaReferenceEnumTrait;

    case BIASA_TUNAI = '1';
    case BERKALA = '2';
    case DENGAN_JAMINAN = '3';
    case PERHITUNGAN_KEMUDIAN = '4';
    case KONSINYASI_CONSIGNMENT = '5';
    case USANCE_LETTER_OF_CREDIT = '6';
    case RED_CLAUSE_LETTER_OF_CREDIT = '7';
    case INTER_COMPANY_ACCOUNT = '8';
    case GABUNGAN_LAINNYA = '9';
    case PEMBAYARAN_KEMUDIAN_OPEN_ACCOUNT_SECARA_BERTAHAP = '10';
    case PEMBAYARAN_KEMUDIAN_OPEN_ACCOUNT_SECARA_TUNAI = '11';
    case DILAKUKAN_DI_DN_DENGAN_PEMBAYARAN_UANG_TUNAI = '12';
    case DILAKUKAN_DI_DN_DENGAN_PEMBAYARAN_MELALUI_TELEGRAPH = '13';
    case DILAKUKAN_TANPA_PEMBAYARAN = '14';
    case PEMBAYARAN_DIMUKA_ADVANCE_PAYMENT = '15';
    case SIGHT_LETTER_OF_CREDIT = '16';
    case INKASO_COLLECTION_DRAFT = '17';

    /**
     * Mendapatkan deskripsi / uraian resmi dari DJBC untuk kode referensi ini.
     */
    public function description(): string
    {
        return match ($this) {
            self::BIASA_TUNAI => 'BIASA/TUNAI',
            self::BERKALA => 'BERKALA',
            self::DENGAN_JAMINAN => 'DENGAN JAMINAN',
            self::PERHITUNGAN_KEMUDIAN => 'PERHITUNGAN KEMUDIAN',
            self::KONSINYASI_CONSIGNMENT => 'KONSINYASI (CONSIGNMENT)',
            self::USANCE_LETTER_OF_CREDIT => 'USANCE LETTER OF CREDIT',
            self::RED_CLAUSE_LETTER_OF_CREDIT => 'RED CLAUSE LETTER OF CREDIT',
            self::INTER_COMPANY_ACCOUNT => 'INTER-COMPANY ACCOUNT',
            self::GABUNGAN_LAINNYA => 'GABUNGAN/LAINNYA',
            self::PEMBAYARAN_KEMUDIAN_OPEN_ACCOUNT_SECARA_BERTAHAP => 'PEMBAYARAN KEMUDIAN (OPEN ACCOUNT) SECARA BERTAHAP',
            self::PEMBAYARAN_KEMUDIAN_OPEN_ACCOUNT_SECARA_TUNAI => 'PEMBAYARAN KEMUDIAN (OPEN ACCOUNT) SECARA TUNAI',
            self::DILAKUKAN_DI_DN_DENGAN_PEMBAYARAN_UANG_TUNAI => 'DILAKUKAN DI DN DENGAN PEMBAYARAN UANG TUNAI',
            self::DILAKUKAN_DI_DN_DENGAN_PEMBAYARAN_MELALUI_TELEGRAPH => 'DILAKUKAN DI DN DENGAN PEMBAYARAN MELALUI TELEGRAPH',
            self::DILAKUKAN_TANPA_PEMBAYARAN => 'DILAKUKAN TANPA PEMBAYARAN',
            self::PEMBAYARAN_DIMUKA_ADVANCE_PAYMENT => 'PEMBAYARAN DIMUKA (ADVANCE PAYMENT)',
            self::SIGHT_LETTER_OF_CREDIT => 'SIGHT LETTER OF CREDIT',
            self::INKASO_COLLECTION_DRAFT => 'INKASO (COLLECTION DRAFT)',
        };
    }
}
